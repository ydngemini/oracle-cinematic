"""Audit 35-01: backend/requirements.txt is the hash-locked compile of
requirements.in, so every build installs the same artifacts and the scan sees
every version. This fails when the two drift (a pin edited in one only)."""

from __future__ import annotations

import re
from pathlib import Path

from packaging.requirements import Requirement
from packaging.utils import canonicalize_name

BACKEND = Path(__file__).resolve().parents[1]


def _direct() -> list[Requirement]:
    reqs = []
    for line in (BACKEND / "requirements.in").read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line and not line.startswith("-"):
            reqs.append(Requirement(line))
    return reqs


def _locked() -> dict[str, tuple[str, int]]:
    text = (BACKEND / "requirements.txt").read_text()
    out = {}
    for block in re.split(r"\n(?=[A-Za-z0-9])", text):
        m = re.match(r"([A-Za-z0-9][A-Za-z0-9._-]*)==([^\s\;]+)", block)
        if m:
            out[canonicalize_name(m.group(1))] = (m.group(2), block.count("--hash=sha256:"))
    return out


def test_the_lock_is_a_pip_compile_output():
    assert "autogenerated by pip-compile" in (BACKEND / "requirements.txt").read_text()[:400]


def test_every_locked_package_is_exact_and_hashed():
    locked = _locked()
    assert len(locked) > 50
    unhashed = [name for name, (_v, hashes) in locked.items() if hashes == 0]
    assert unhashed == []


def test_every_direct_dependency_is_locked_at_a_version_it_allows():
    locked = _locked()
    problems = []
    for req in _direct():
        name = canonicalize_name(req.name)
        if name not in locked:
            problems.append(f"{req.name}: missing from requirements.txt")
        elif req.specifier and not req.specifier.contains(locked[name][0], prereleases=True):
            problems.append(f"{req.name}: requirements.in says {req.specifier}, lock has {locked[name][0]}")
    assert problems == [], "run scripts/lock-python-deps.sh: " + "; ".join(problems)
