"""A site's custom domain moves only on DNS evidence, and a rollback re-points
the live revision, which the public route then serves (prompt 14, T14.04,
AC14.04, F14.04/AC14.08, F14.07; 0173), against real PostgreSQL with FORCE
RLS, as the request login (skipped without ORACLE_LIVE_DB_ADMIN_DSN).

The resolver is a stub: no test here makes a DNS or network call.

Actors in brokerage A: the broker owner; the agent who owns the site; a
collaborator who may publish; a collaborator who may only edit; a colleague
with no grant. Brokerage B: its broker owner, with a site of its own.

Pins:
  * an edit-only collaborator's new revision or preview never takes the live
    site offline;
  * the colleague, the edit-only collaborator and the other brokerage get 404
    on the domain list, the DNS check and the rollback, before any lookup;
  * a hostname claimed by one brokerage cannot be claimed by another (409,
    their publish rolls back whole) and is invisible to it;
  * pending stays pending without a record; an unreachable resolver writes
    nothing and says retryable; a matching TXT verifies; without the
    operator's serving target the claim never goes active; with it, a CNAME
    onto the target makes it active; a vanished record fails it; a pending or
    failed claim whose TXT and CNAME both match goes active in one check,
    written through verified (the trail shows both moves); a move the database
    refuses is a 409 that writes nothing, never a 500; a republish never
    resets the state, and its audit entry names the claim's real state;
  * the database refuses illegal moves, a verified state without its
    evidence, a claim that changes hostname, and a claim born verified; the
    token is generated by PostgreSQL for the application role;
  * rollback is guarded by the live version the caller saw, restores only a
    revision that was live before, replays without a second effect, never
    edits a revision, and the public route serves the restored revision at
    once with a new ETag; archive is 404 (no-store) at once;
  * every transition is an immutable event naming who made it; the
    application can neither write nor change one.
"""

from __future__ import annotations

import asyncio
import logging
import hashlib
import os
import uuid

import pytest

DSN = os.getenv("ORACLE_LIVE_DB_ADMIN_DSN", "")
pytestmark = pytest.mark.skipif(not DSN, reason="needs ORACLE_LIVE_DB_ADMIN_DSN (real PostgreSQL)")

TARGET = "sites.neoh-live-test.example"


def test_domains_move_on_evidence_and_rollback_is_served(monkeypatch, caplog):
    asyncio.run(_scenario(monkeypatch, caplog))


class StubResolver:
    def __init__(self):
        self.txt: list[str] = []
        self.cname: list[str] = []
        self.unreachable = False
        self.calls: list[tuple[str, str]] = []

    async def lookup(self, name, rdtype):
        import site_domains

        self.calls.append((name, rdtype))
        if self.unreachable:
            raise site_domains.DnsUnavailable("stub resolver unreachable")
        return list(self.txt if rdtype == "TXT" else self.cname)


async def _scenario(monkeypatch, caplog):  # noqa: C901 — one scenario, read top to bottom
    import asyncpg
    from fastapi import HTTPException
    from starlette.requests import Request
    from starlette.responses import Response

    import approval_service
    import audit_ledger
    import public_sites_api as ps
    import site_domains
    import sites_api
    from db import connection
    from tenancy import Role, TenantContext

    audited: list[dict] = []

    async def record(**kwargs):
        audited.append(kwargs)

    monkeypatch.setattr(audit_ledger.ledger, "record", record)
    monkeypatch.delenv("ORACLE_SITES_DOMAIN_TARGET", raising=False)
    monkeypatch.setattr(sites_api, "_RECHECK_SECONDS", 0)

    admin = await asyncpg.connect(DSN)
    await connection.init_pool(min_size=1, max_size=3)
    tenant, other = str(uuid.uuid4()), str(uuid.uuid4())
    tslug, oslug = f"dom-{tenant[:8]}", f"dom-{other[:8]}"
    host = f"homes-{tenant[:8]}.example.com"

    def ctx(name, role=Role.AGENT, tid=None):
        return TenantContext(agent_id=f"{name}-{tenant[:8]}@sites.test", tenant_id=tid or tenant, role=role)

    owner, agent = ctx("owner", Role.BROKER_OWNER), ctx("agent")
    publisher, editor, colleague = ctx("publisher"), ctx("editor"), ctx("colleague")
    owner_b = ctx("owner-b", Role.BROKER_OWNER, other)
    resolver = StubResolver()
    req = Request({"type": "http", "method": "GET", "path": "/", "headers": []})

    def conditional(etag):
        return Request({"type": "http", "method": "GET", "path": "/", "headers": [(b"if-none-match", etag.encode())]})

    async def publish(site_id, revision_id, by, decider, hostname=host):
        asked = await sites_api.request_site_publish(
            site_id, sites_api.SitePublishRequest(revision_id=revision_id, hostname=hostname), ctx=by)
        await approval_service.decide_approval(decider, asked["approval"]["id"], decision="approved",
                                               reason="Reviewed the page content for publishing")
        return await sites_api.publish_site(site_id, sites_api.SitePublishFinalize(
            revision_id=revision_id, hostname=hostname, approval_id=asked["approval"]["id"]), ctx=by)

    def content(headline):
        return sites_api.SiteContent(
            headline=headline, description="Source-backed local guidance for Dover buyers and sellers.",
            seo_title="Dover homes", seo_description="Local guidance for Dover home buyers and sellers here.")

    async def events(site_id, subject):
        rows = await admin.fetch(
            "SELECT from_status, to_status, from_revision_id, to_revision_id, actor, actor_role, evidence, source "
            "FROM hyperlocal_site_events WHERE site_id=$1 AND subject=$2 ORDER BY occurred_at, id", site_id, subject)
        return [dict(r) for r in rows]

    async def domain_row(domain_id):
        return dict(await admin.fetchrow("SELECT * FROM hyperlocal_site_domains WHERE id=$1", domain_id))

    async def served(slug=None, tenant_slug=None):
        response = Response()
        body = await ps.public_site(tenant_slug or tslug, slug or "dover-live", req, response)
        return body, response.headers.get("etag")

    try:
        for tid, slug in ((tenant, tslug), (other, oslug)):
            await admin.execute("INSERT INTO tenants (id, slug, name) VALUES ($1,$2,'Site domains')", uuid.UUID(tid), slug)
        for who in (owner, agent, publisher, editor, colleague, owner_b):
            await admin.execute("INSERT INTO users (tenant_id, agent_id, role, email) VALUES ($1,$2,$3,$2)",
                                uuid.UUID(who.tenant_id), who.agent_id, who.role.value)

        # ── the agent's site, two collaborators, v1 published with a hostname ─
        created = await sites_api.create_site(sites_api.SiteCreate(name="Dover Live", slug="dover-live"), ctx=agent)
        site_id = uuid.UUID(created["site"]["id"])
        v1 = uuid.UUID(created["revision"]["id"])
        for who, can_publish in ((publisher, True), (editor, False)):
            await sites_api.upsert_site_collaborator(site_id, who.agent_id, sites_api.SiteCollaboratorUpsert(
                agent_id=who.agent_id, can_edit=True, can_publish=can_publish), ctx=agent)
        published = await publish(site_id, v1, agent, owner)
        domain = published["domain"]
        domain_id = uuid.UUID(domain["id"])
        assert domain["status"] == "pending" and published["custom_domain_status"] == "pending_verification"
        token = (await domain_row(domain_id))["challenge_token"]
        assert len(token) == 64 and int(token, 16) >= 0
        assert published["dns_challenge"] == {"type": "TXT", "name": f"_neoh-site-verify.{host}",
                                              "value": f"neoh-site-verify={token}"}
        body, etag_v1 = await served()
        assert body["revision"] == 1

        # ── an edit-only collaborator's revision and preview leave it live ───
        v2 = uuid.UUID((await sites_api.create_site_revision(site_id, sites_api.SiteRevisionCreate(
            brand_theme=sites_api.BrandTheme(), content=content("Dover homes, second edition")), ctx=editor))
            ["revision"]["id"])
        await sites_api.preview_site(site_id, sites_api.SitePreviewRequest(revision_id=v2), ctx=editor)
        assert await admin.fetchval("SELECT status FROM hyperlocal_sites WHERE id=$1", site_id) == "published"
        assert (await served())[0]["revision"] == 1

        # ── nobody without the publish right reaches a domain or a rollback ──
        rollback_v1 = sites_api.SiteRollbackRequest(expected_live_revision_id=v1)
        for who in (colleague, editor, owner_b):
            for call in (lambda: sites_api.list_site_domains(site_id, ctx=who),
                         lambda: sites_api.verify_site_domain(site_id, domain_id, ctx=who, resolver=resolver),
                         lambda: sites_api.rollback_site(site_id, rollback_v1, ctx=who)):
                with pytest.raises(HTTPException) as denied:
                    await call()
                assert denied.value.status_code == 404, who.agent_id
        assert resolver.calls == []
        async with connection.tenant_tx(owner_b) as conn:
            assert await conn.fetchval("SELECT count(*) FROM hyperlocal_site_domains WHERE hostname=$1", host) == 0
            assert await conn.fetchval("SELECT count(*) FROM hyperlocal_site_events WHERE site_id=$1", site_id) == 0
        assert (await sites_api.get_site(site_id, ctx=editor))["can_publish"] is False

        # ── another brokerage cannot claim the hostname ──────────────────────
        theirs = await sites_api.create_site(sites_api.SiteCreate(name="Their Site", slug="their-site"), ctx=owner_b)
        with pytest.raises(HTTPException) as taken:
            await publish(uuid.UUID(theirs["site"]["id"]), uuid.UUID(theirs["revision"]["id"]), owner_b, owner_b)
        assert (taken.value.status_code, taken.value.detail) == (409, "This hostname is not available.")
        assert await admin.fetchval("SELECT status FROM hyperlocal_sites WHERE id=$1",
                                    uuid.UUID(theirs["site"]["id"])) == "draft"     # the whole publish rolled back
        assert await admin.fetchval("SELECT tenant_id FROM hyperlocal_site_domains WHERE hostname=$1", host) == \
            uuid.UUID(tenant)

        # ── the DNS check, step by step, by the publishing collaborator ──────
        listed = await sites_api.list_site_domains(site_id, ctx=publisher)
        assert [d["status"] for d in listed["domains"]] == ["pending"]
        assert listed["domains"][0]["challenge"] == published["dns_challenge"]
        assert listed["serving"] == {"available": False, "target": None}

        async def check():
            return await sites_api.verify_site_domain(site_id, domain_id, ctx=publisher, resolver=resolver)

        result = await check()                                     # no record yet
        assert (result["outcome"], result["domain"]["status"], result["retryable"]) == \
            ("record_not_found", "pending", False)
        assert (await domain_row(domain_id))["last_checked_at"] is not None

        before = await domain_row(domain_id)
        resolver.unreachable = True                               # unknown is not failure
        result = await check()
        assert (result["outcome"], result["retryable"], result["retry_after_seconds"]) == ("dns_unavailable", True, 30)
        assert "Nothing changed" in result["message"]
        assert await domain_row(domain_id) == before
        resolver.unreachable = False

        resolver.txt = ["v=spf1 -all", f"neoh-site-verify={token}"]
        resolver.cname = [TARGET]
        result = await check()                                     # ownership proven; no serving target
        row = await domain_row(domain_id)
        assert (result["outcome"], row["status"]) == ("verified", "verified")
        assert row["verified_at"] is not None
        assert row["verification_hash"] == hashlib.sha256(f"neoh-site-verify={token}".encode()).hexdigest()
        assert "not set up on this platform" in result["message"]
        assert (await check())["domain"]["status"] == "verified"   # never active without the operator's target

        monkeypatch.setenv("ORACLE_SITES_DOMAIN_TARGET", TARGET)
        result = await check()
        assert (result["outcome"], result["domain"]["status"]) == ("active", "active")

        resolver.txt = ["v=spf1 -all"]                  # the record is gone; only a wildcard SPF answers
        result = await check()
        row = await domain_row(domain_id)
        assert (result["outcome"], row["status"], row["verified_at"]) == ("record_not_found", "failed", None)
        resolver.txt = [f"neoh-site-verify={token}"]   # back, with the CNAME still on the target:
        result = await check()                          # failed -> verified -> active, one check
        row = await domain_row(domain_id)
        assert (result["outcome"], result["domain"]["status"], row["status"]) == ("active", "active", "active")
        assert row["verified_at"] is not None and row["verification_hash"] is not None
        resolver.cname = []
        assert (await check())["domain"]["status"] == "verified"  # proven, but no longer pointed at the target

        monkeypatch.setattr(sites_api, "_RECHECK_SECONDS", 3600)   # the cost bound
        calls = len(resolver.calls)
        with pytest.raises(HTTPException) as soon:
            await check()
        assert soon.value.status_code == 429 and len(resolver.calls) == calls
        monkeypatch.setattr(sites_api, "_RECHECK_SECONDS", 0)

        trail = await events(site_id, "domain")
        assert [(e["from_status"], e["to_status"]) for e in trail] == [
            (None, "pending"), ("pending", "verified"), ("verified", "active"), ("active", "failed"),
            ("failed", "verified"), ("verified", "active"), ("active", "verified")]
        assert {e["actor"] for e in trail} == {agent.agent_id, publisher.agent_id}
        assert all(e["actor"] == publisher.agent_id and e["actor_role"] == "agent" for e in trail[1:])
        assert trail[1]["evidence"] and '"outcome": "verified"' in trail[1]["evidence"]
        checked = [a for a in audited if a["action"] == "studio_site_domain_checked"]
        assert checked and all(host not in repr(a) for a in checked)

        # ── the database holds the line without the route ────────────────────
        async def as_owner(sql, *args):
            async with connection.tenant_tx(owner) as conn:
                return await conn.fetchrow(sql, *args)

        fresh = await as_owner("INSERT INTO hyperlocal_site_domains (tenant_id, site_id, hostname) "
                               "VALUES ($1::uuid,$2,$3) RETURNING id, status, challenge_token",
                               tenant, site_id, f"second-{host}")
        assert fresh["status"] == "pending" and len(fresh["challenge_token"]) == 64
        assert fresh["challenge_token"] != token
        for sql, args in (
            ("UPDATE hyperlocal_site_domains SET status='active', verified_at=now(), verification_hash=$2 "
             "WHERE id=$1", (fresh["id"], "f" * 64)),                                          # no path to active
            ("UPDATE hyperlocal_site_domains SET status='pending' WHERE id=$1", (domain_id,)),  # no way back
            ("UPDATE hyperlocal_site_domains SET hostname='elsewhere.example.com' WHERE id=$1", (domain_id,)),
            ("UPDATE hyperlocal_site_domains SET challenge_token=$2 WHERE id=$1", (domain_id, "0" * 64)),
        ):
            with pytest.raises(asyncpg.CheckViolationError):
                await as_owner(sql, *args)
        with pytest.raises(asyncpg.CheckViolationError):                           # verified needs its evidence
            await as_owner("UPDATE hyperlocal_site_domains SET status='verified' WHERE id=$1", fresh["id"])
        with pytest.raises(asyncpg.CheckViolationError):                           # a claim is born pending
            await as_owner("INSERT INTO hyperlocal_site_domains (tenant_id, site_id, hostname, status, verified_at, "
                           "verification_hash) VALUES ($1::uuid,$2,$3,'verified',now(),$4)",
                           tenant, site_id, f"third-{host}", "e" * 64)

        # ── a pending claim whose TXT and CNAME are both in place ────────────
        # The target is set and the owner added both records, the usual setup:
        # one check takes it to active, written through verified.
        resolver.txt, resolver.cname = [f"neoh-site-verify={fresh['challenge_token']}"], [TARGET]

        async def check_fresh():
            return await sites_api.verify_site_domain(site_id, fresh["id"], ctx=publisher, resolver=resolver)

        steps = site_domains.steps
        monkeypatch.setattr(site_domains, "steps", lambda current, status: [status])   # a direct pending -> active
        before = await domain_row(fresh["id"])
        with pytest.raises(HTTPException) as refused:              # the database refuses it: 409, not 500
            await check_fresh()
        assert refused.value.status_code == 409
        assert await domain_row(fresh["id"]) == before              # and nothing was written
        # The code and the trigger disagreeing is a defect to find: logged with
        # ids and statuses only (never the hostname), not a silent 409.
        (logged,) = [r for r in caplog.records
                     if r.name == "sites_api" and r.levelno >= logging.ERROR]
        assert str(fresh["id"]) in logged.getMessage() and "pending" in logged.getMessage()
        assert "active" in logged.getMessage() and "23514" in logged.getMessage()
        assert host not in logged.getMessage()
        monkeypatch.setattr(site_domains, "steps", steps)
        result = await check_fresh()
        assert (result["outcome"], result["domain"]["status"]) == ("active", "active")
        fresh_trail = [dict(r) for r in await admin.fetch(
            "SELECT from_status, to_status, actor, evidence FROM hyperlocal_site_events "
            "WHERE domain_id=$1 ORDER BY occurred_at, id", fresh["id"])]
        assert [(e["from_status"], e["to_status"]) for e in fresh_trail] == [
            (None, "pending"), ("pending", "verified"), ("verified", "active")]
        assert [e["actor"] for e in fresh_trail[1:]] == [publisher.agent_id, publisher.agent_id]
        assert '"outcome": "verified"' in fresh_trail[1]["evidence"]
        assert '"outcome": "active"' in fresh_trail[2]["evidence"]

        # ── v2 published by the collaborator; the republish keeps the state ──
        republished = await publish(site_id, v2, publisher, owner)
        assert republished["domain"]["status"] == "verified"
        published_audit = [a["metadata"] for a in audited if a["action"] == "studio_site_published"]
        assert [m.get("custom_domain_status") for m in published_audit] == ["pending", "verified"]
        assert not any("custom_domain_pending" in m for m in published_audit)
        body, etag_v2 = await served()
        assert body["revision"] == 2 and etag_v2 != etag_v1
        detail = await sites_api.get_site(site_id, ctx=publisher)
        assert detail["can_publish"] is True
        assert detail["publication"] == {"status": "published", "live_revision_id": str(v2),
                                         "rollback_to_revision_id": str(v1)}

        # ── rollback ─────────────────────────────────────────────────────────
        revisions_before = [dict(r) for r in await admin.fetch(
            "SELECT * FROM hyperlocal_site_revisions WHERE site_id=$1 ORDER BY revision", site_id)]
        with pytest.raises(HTTPException) as stale:
            await sites_api.rollback_site(site_id, rollback_v1, ctx=agent)      # saw v1 live; v2 is
        assert stale.value.status_code == 409
        v3 = uuid.UUID((await sites_api.create_site_revision(site_id, sites_api.SiteRevisionCreate(
            brand_theme=sites_api.BrandTheme(), content=content("Dover homes, an unpublished draft")), ctx=agent))
            ["revision"]["id"])
        with pytest.raises(HTTPException) as never:
            await sites_api.rollback_site(site_id, sites_api.SiteRollbackRequest(
                expected_live_revision_id=v2, to_revision_id=v3), ctx=agent)
        assert never.value.status_code == 409 and "never published" in never.value.detail

        rolled = await sites_api.rollback_site(
            site_id, sites_api.SiteRollbackRequest(expected_live_revision_id=v2), ctx=agent)
        assert (rolled["live_revision_id"], rolled["previous_live_revision_id"], rolled["already_live"]) == \
            (str(v1), str(v2), False)
        body, etag_back = await served()                          # served at once
        assert body["revision"] == 1 and etag_back != etag_v2
        assert isinstance(await ps.public_site(tslug, "dover-live", conditional(etag_v2), Response()), dict)
        replay = await sites_api.rollback_site(site_id, sites_api.SiteRollbackRequest(
            expected_live_revision_id=v2, to_revision_id=v1), ctx=agent)
        assert replay["already_live"] is True

        site_trail = await events(site_id, "site")
        assert [(e["from_status"], e["to_status"], e["from_revision_id"], e["to_revision_id"]) for e in site_trail] == [
            (None, "draft", None, None),
            ("draft", "published", None, v1),
            ("published", "published", v1, v2),
            ("published", "published", v2, v1),
        ]
        assert [e["actor"] for e in site_trail[1:]] == [agent.agent_id, publisher.agent_id, agent.agent_id]
        assert '"approved_by"' in site_trail[1]["evidence"] and owner.agent_id in site_trail[1]["evidence"]
        assert '"rollback": true' in site_trail[3]["evidence"]
        revisions_after = [dict(r) for r in await admin.fetch(
            "SELECT * FROM hyperlocal_site_revisions WHERE site_id=$1 ORDER BY revision", site_id)]
        assert revisions_after[:len(revisions_before)] == revisions_before          # nothing edited, v1 included
        rolled_audit = [a for a in audited if a["action"] == "studio_site_rolled_back"]
        assert rolled_audit[-1]["metadata"]["to_revision_id"] == str(v1)
        assert rolled_audit[-1]["user_id"] == agent.agent_id

        # ── revisions and the trail are immutable ────────────────────────────
        with pytest.raises(asyncpg.InsufficientPrivilegeError):
            await as_owner("UPDATE hyperlocal_site_revisions SET content='{}'::jsonb WHERE id=$1", v1)
        with pytest.raises(asyncpg.InsufficientPrivilegeError, match="immutable"):
            await admin.execute("UPDATE hyperlocal_site_revisions SET content='{}'::jsonb WHERE id=$1", v1)
        for sql in ("INSERT INTO hyperlocal_site_events (tenant_id, site_id, subject, to_status, actor) "
                    "VALUES ($1::uuid,$2,'site','published','forged')",
                    "UPDATE hyperlocal_site_events SET actor='forged' WHERE site_id=$2 AND $1::uuid IS NOT NULL",
                    "DELETE FROM hyperlocal_site_events WHERE site_id=$2 AND $1::uuid IS NOT NULL"):
            with pytest.raises(asyncpg.InsufficientPrivilegeError):
                await as_owner(sql, tenant, site_id)
        with pytest.raises(asyncpg.InsufficientPrivilegeError, match="append-only"):
            await admin.execute("UPDATE hyperlocal_site_events SET actor='x' WHERE site_id=$1", site_id)

        # ── archive: gone from the public route at once, and nothing to do ───
        await admin.execute("UPDATE hyperlocal_sites SET status='archived' WHERE id=$1", site_id)
        with pytest.raises(HTTPException) as gone:
            await served()
        assert gone.value.status_code == 404 and gone.value.headers == {"Cache-Control": "no-store"}
        calls = len(resolver.calls)
        for call in (lambda: sites_api.rollback_site(site_id, sites_api.SiteRollbackRequest(
                         expected_live_revision_id=v1, to_revision_id=v2), ctx=agent),
                     lambda: sites_api.verify_site_domain(site_id, domain_id, ctx=agent, resolver=resolver)):
            with pytest.raises(HTTPException) as archived:
                await call()
            assert archived.value.status_code == 404
        assert len(resolver.calls) == calls
        assert (await events(site_id, "site"))[-1]["to_status"] == "archived"
    finally:
        await admin.execute("SET session_replication_role = replica")
        try:
            for tid in (tenant, other):
                for table in ("hyperlocal_site_events", "hyperlocal_site_domains", "hyperlocal_site_collaborators",
                              "hyperlocal_site_revisions", "hyperlocal_sites", "ai_decision_traces",
                              "action_approvals", "users"):
                    await admin.execute(f"DELETE FROM {table} WHERE tenant_id = $1", uuid.UUID(tid))
                await admin.execute("DELETE FROM tenants WHERE id = $1", uuid.UUID(tid))
        finally:
            await admin.execute("SET session_replication_role = origin")
            await admin.close()
            await connection.close_pool()
