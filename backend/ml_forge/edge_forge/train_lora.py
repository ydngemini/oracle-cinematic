def main():
    parser = argparse.ArgumentParser(description="Edge Forge LoRA trainer")
    parser.add_argument("--state", default="DE", help="State code for the adapter (e.g. DE)")
    parser.add_argument("--data", default=DEFAULT_DATA_PATH, help="Path to JSONL training corpus")
    parser.add_argument("--max-steps", type=int, default=60, help="Training steps")
    parser.add_argument(
        "--style-examples",
        help="Opt-in JSONL examples to redact and train as an agent style adapter",
    )
    parser.add_argument("--agent", help="Agent id owning the consented style examples")
    parser.add_argument("--consent-version", help="Version of the recorded opt-in consent")
    args = parser.parse_args()

    data_path = args.data
    manifest: dict[str, Any] = underwriting_manifest(data_path)
    if args.style_examples:
        if not args.agent or not args.consent_version:
            parser.error("--style-examples requires --agent and --consent-version")
        examples = []
        with open(args.style_examples, "r", encoding="utf-8") as handle:
            for line in handle:
                if line.strip():
                    examples.append(json.loads(line))
        prepared = os.path.join(
            OUTPUT_DIR, "datasets", f"agent-{args.agent}-redacted.jsonl"
        )
        manifest = prepare_consented_style_dataset(
            examples,
            agent_id=args.agent,
            consent_version=args.consent_version,
            output_path=prepared,
        )
        manifest["kind"] = "consented_agent_style"
        data_path = prepared

    gguf_path = train(data_path, args.state, args.max_steps)
    card = model_card_for(
        manifest,
        name=f"{'agent-' + args.agent if args.agent else args.state.lower()}-lora",
        steps=args.max_steps,
    )
    card_path = Path(gguf_path).with_suffix(".model-card.json")
    card_path.write_text(json.dumps(card, indent=2, sort_keys=True), encoding="utf-8")
    # The adapter carries its own card: EdgeUnderwriter mounts a state adapter
    # only when that card declares observed-transaction targets.
    Path(adapter_dir_for(args.state), ADAPTER_CARD).write_text(
        json.dumps(card, indent=2, sort_keys=True), encoding="utf-8"
    )
    print(f"[edge_forge] Done. Edge artifact: {gguf_path}")
    print(f"[edge_forge] Artifact SHA-256: {artifact_sha256(gguf_path)}")
    print(f"[edge_forge] Model card: {card_path}")


