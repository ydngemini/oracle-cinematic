LOAD_IN_4BIT = True

# LoRA — adapt only the attention projections, per the edge-forge spec.
LORA_RANK = 16
LORA_ALPHA = 16
TARGET_MODULES = ["q_proj", "k_proj", "v_proj", "o_proj"]

