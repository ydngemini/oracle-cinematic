"""Edge Forge — consented, auditable LoRA fine-tuning.

Trains a Llama-3-8B-Instruct LoRA on Delaware wholesale assignment contracts
(generated by synthetic_lawyer.py) using unsloth's 2x-faster 4-bit pipeline,
then exports a quantized .gguf for edge inference via llama.cpp / vLLM.

The resulting adapter is one "state lobe" — hot-swapped at inference time by
EdgeUnderwriter.hot_swap_state_lora() in local_vllm_adapter.py.

Usage:
    python -m backend.ml_forge.edge_forge.train_lora --state DE

Requires (install into the ml_forge venv, GPU recommended):
    pip install "unsloth[colab-new] @ git+https://github.com/unslothai/unsloth.git"
    pip install --no-deps trl peft accelerate bitsandbytes
"""

