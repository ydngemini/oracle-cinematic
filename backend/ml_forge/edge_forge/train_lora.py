def adapter_dir_for(state_code: str) -> str:
    """Where train() leaves the raw LoRA adapter — the directory
    EdgeUnderwriter discovers state adapters in."""
    return os.path.join(OUTPUT_DIR, "adapters", state_code.lower())


def train(data_path: str, state_code: str, max_steps: int) -> str:
    """Fine-tune the LoRA adapter and export a .gguf. Returns the gguf path."""
    try:
        from unsloth import FastLanguageModel
        from unsloth.chat_templates import get_chat_template
        from trl import SFTTrainer
        from transformers import TrainingArguments
    except ImportError as exc:
        raise RuntimeError(
            "GPU training dependencies are unavailable; submit this manifest to the RunPod training image"
        ) from exc
    model, tokenizer = FastLanguageModel.from_pretrained(
        model_name=BASE_MODEL,
        max_seq_length=MAX_SEQ_LENGTH,
        dtype=None,            # auto-detect (bf16 on Ampere+, else fp16)
        load_in_4bit=LOAD_IN_4BIT,
    )

    tokenizer = get_chat_template(tokenizer, chat_template="llama-3")

    model = FastLanguageModel.get_peft_model(
        model,
        r=LORA_RANK,
        target_modules=TARGET_MODULES,
        lora_alpha=LORA_ALPHA,
        lora_dropout=0.0,
        bias="none",
        use_gradient_checkpointing="unsloth",
        random_state=3407,
    )

    dataset = load_training_dataset(data_path, tokenizer)

    trainer = SFTTrainer(
        model=model,
        tokenizer=tokenizer,
        train_dataset=dataset,
        dataset_text_field="text",
        max_seq_length=MAX_SEQ_LENGTH,
        packing=False,
        args=TrainingArguments(
            per_device_train_batch_size=2,
            gradient_accumulation_steps=4,
            warmup_steps=5,
            max_steps=max_steps,
            learning_rate=2e-4,
            fp16=not _bf16_supported(),
            bf16=_bf16_supported(),
            logging_steps=1,
            optim="adamw_8bit",
            weight_decay=0.01,
            lr_scheduler_type="linear",
            seed=3407,
            output_dir=os.path.join(OUTPUT_DIR, "checkpoints", state_code.lower()),
            report_to="none",
        ),
    )

    trainer.train()

    # Export a merged, quantized GGUF for edge inference.
    gguf_dir = os.path.join(OUTPUT_DIR, "gguf", state_code.lower())
    os.makedirs(gguf_dir, exist_ok=True)
    model.save_pretrained_gguf(
        gguf_dir,
        tokenizer,
        quantization_method=GGUF_QUANT_METHOD,
    )

    # Also persist the raw LoRA adapter so vLLM can hot-swap it without a merge.
    adapter_dir = adapter_dir_for(state_code)
    model.save_pretrained(adapter_dir)
    tokenizer.save_pretrained(adapter_dir)

    gguf_path = os.path.join(gguf_dir, f"unsloth.{GGUF_QUANT_METHOD.upper()}.gguf")
    print(f"[edge_forge] GGUF written under: {gguf_dir}")
    print(f"[edge_forge] LoRA adapter written to: {adapter_dir}")
    return gguf_path


def _bf16_supported() -> bool:
    try:
        import torch
        return torch.cuda.is_available() and torch.cuda.is_bf16_supported()
    except Exception:
        return False


